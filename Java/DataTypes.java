public class DataTypes {
    public static void main(String[] args) {
        int a = 5;
        byte b = 100;
        float c = 5.5f;
        double d = 5.5;
        char e = '@';
        int g = 10;
        double f = 5.4;

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
        System.out.printf("%d", g);
        System.out.println();
        System.out.printf("%f", f);
    }
    
}
